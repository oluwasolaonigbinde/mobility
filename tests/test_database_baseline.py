def test_canonical_alembic_check_detects_visible_schema_drift(monkeypatch) -> None:
    source_url = configured_postgres_url()
    migration_url = asyncio.run(create_database_from_url(source_url))
    mutations = [
        (
            "index",
            "DROP INDEX ix_vehicles_status",
            "CREATE INDEX ix_vehicles_status ON vehicles (status)",
            lambda diff: diff[0] == "add_index" and diff[1].name == "ix_vehicles_status",
        ),
        (
            "unique constraint",
            "ALTER TABLE users DROP CONSTRAINT uq_users_email",
            "ALTER TABLE users ADD CONSTRAINT uq_users_email UNIQUE (email)",
            lambda diff: diff[0] == "add_constraint" and diff[1].name == "uq_users_email",
        ),
        (
            "foreign key",
            "ALTER TABLE vehicles DROP CONSTRAINT vehicles_driver_profile_id_fkey",
            "ALTER TABLE vehicles ADD CONSTRAINT vehicles_driver_profile_id_fkey "
            "FOREIGN KEY (driver_profile_id) REFERENCES driver_profiles(id) ON DELETE CASCADE",
            lambda diff: (
                diff[0] == "add_fk"
                and diff[1].table.name == "vehicles"
                and tuple(diff[1].columns.keys()) == ("driver_profile_id",)
            ),
        ),
        (
            "column type",
            "ALTER TABLE users ALTER COLUMN full_name TYPE text",
            "ALTER TABLE users ALTER COLUMN full_name TYPE varchar(255)",
            lambda diff: diff[0] == "modify_type" and diff[2:4] == ("users", "full_name"),
        ),
        (
            "JSON subtype",
            (
                "ALTER TABLE campaigns ALTER COLUMN metadata DROP DEFAULT",
                "ALTER TABLE campaigns ALTER COLUMN metadata TYPE json USING metadata::json",
                "ALTER TABLE campaigns ALTER COLUMN metadata SET DEFAULT '{}'::json",
            ),
            (
                "ALTER TABLE campaigns ALTER COLUMN metadata DROP DEFAULT",
                "ALTER TABLE campaigns ALTER COLUMN metadata TYPE jsonb USING metadata::jsonb",
                "ALTER TABLE campaigns ALTER COLUMN metadata SET DEFAULT '{}'::jsonb",
            ),
            lambda diff: diff[0] == "modify_type" and diff[2:4] == ("campaigns", "metadata"),
        ),
        (
            "server default",
            "ALTER TABLE users ALTER COLUMN must_change_password SET DEFAULT true",
            "ALTER TABLE users ALTER COLUMN must_change_password SET DEFAULT false",
            lambda diff: (
                diff[0] == "modify_default" and diff[2:4] == ("users", "must_change_password")
            ),
        ),
        (
            "JSON server default",
            "ALTER TABLE assignment_activity_flags ALTER COLUMN evidence "
            "SET DEFAULT '{\"drift\": true}'::json",
            "ALTER TABLE assignment_activity_flags ALTER COLUMN evidence SET DEFAULT '{}'::json",
            lambda diff: (
                diff[0] == "modify_default"
                and diff[2:4] == ("assignment_activity_flags", "evidence")
            ),
        ),
    ]
    try:
        upgrade_to(migration_url, "head", monkeypatch)
        for label, apply_statement, restore_statement, detects_mutation in mutations:
            asyncio.run(execute_sql(migration_url, apply_statement))
            try:
                with pytest.raises(AutogenerateDiffsDetected) as exc_info:
                    command.check(Config("alembic.ini"))
                assert any(
                    detects_mutation(diff) for diff in flatten_alembic_diffs(exc_info.value.diffs)
                ), f"canonical Alembic check did not report the {label} mutation"
            finally:
                asyncio.run(execute_sql(migration_url, restore_statement))
            command.check(Config("alembic.ini"))
    finally:
        asyncio.run(drop_database(migration_url))


def test_exact_head_catalog_matches_pk_unique_check_and_geometry_metadata(monkeypatch) -> None:
    source_url = configured_postgres_url()
    migration_url = asyncio.run(create_database_from_url(source_url))
    primary_table = "audit_event_subject_resolutions"
    drop_primary = f"ALTER TABLE {primary_table} DROP CONSTRAINT {primary_table}_pkey"
    add_primary = (
        f"ALTER TABLE {primary_table} ADD CONSTRAINT {primary_table}_pkey PRIMARY KEY (id)"
    )
    mutations = [
        ("primary_keys", primary_table, drop_primary, add_primary),
        (
            "primary_keys",
            primary_table,
            (drop_primary, add_primary + " DEFERRABLE INITIALLY DEFERRED"),
            (drop_primary, add_primary),
        ),
        (
            "primary_keys",
            primary_table,
            (drop_primary, add_primary + " INCLUDE (subject_user_id)"),
            (drop_primary, add_primary),
        ),
        (
            "unique_constraints",
            ("users", "uq_users_email"),
            (
                "ALTER TABLE users DROP CONSTRAINT uq_users_email",
                "ALTER TABLE users ADD CONSTRAINT uq_users_email "
                "UNIQUE (email) DEFERRABLE INITIALLY DEFERRED",
            ),
            (
                "ALTER TABLE users DROP CONSTRAINT uq_users_email",
                "ALTER TABLE users ADD CONSTRAINT uq_users_email UNIQUE (email)",
            ),
        ),
        (
            "unique_constraints",
            ("users", "uq_users_email"),
            (
                "ALTER TABLE users DROP CONSTRAINT uq_users_email",
                "ALTER TABLE users ADD CONSTRAINT uq_users_email "
                "UNIQUE (email) INCLUDE (full_name)",
            ),
            (
                "ALTER TABLE users DROP CONSTRAINT uq_users_email",
                "ALTER TABLE users ADD CONSTRAINT uq_users_email UNIQUE (email)",
            ),
        ),
        (
            "checks",
            ("users", "ck_users_role"),
            (
                "ALTER TABLE users DROP CONSTRAINT ck_users_role",
                "ALTER TABLE users ADD CONSTRAINT ck_users_role "
                "CHECK (role IN ('admin', 'advertiser', 'driver', 'invalid'))",
            ),
            (
                "ALTER TABLE users DROP CONSTRAINT ck_users_role",
                "ALTER TABLE users ADD CONSTRAINT ck_users_role "
                "CHECK (role IN ('admin', 'advertiser', 'driver'))",
            ),
        ),
        (
            "geometry",
            ("campaign_zones", "geom"),
            "ALTER TABLE campaign_zones ALTER COLUMN geom "
            "TYPE geometry(Polygon,4326) USING ST_GeometryN(geom, 1)",
            "ALTER TABLE campaign_zones ALTER COLUMN geom "
            "TYPE geometry(MultiPolygon,4326) USING ST_Multi(geom)",
        ),
        (
            "geometry",
            ("campaign_zones", "geom"),
            "ALTER TABLE campaign_zones ALTER COLUMN geom "
            "TYPE geometry(MultiPolygon,3857) USING ST_Transform(geom, 3857)",
            "ALTER TABLE campaign_zones ALTER COLUMN geom "
            "TYPE geometry(MultiPolygon,4326) USING ST_Transform(geom, 4326)",
        ),
    ]
    try:
        upgrade_to(migration_url, "head", monkeypatch)
        baseline = asyncio.run(fetch_catalog_authority(migration_url))
        assert baseline["actual_primary_keys"] == baseline["expected_primary_keys"]
        assert baseline["actual_unique_constraints"] == baseline["expected_unique_constraints"]
        assert baseline["expected_primary_keys"]["audit_events"] == {
            "key_columns": ("id",),
            "deferrable": False,
            "initially": "IMMEDIATE",
            "included_columns": (),
        }
        assert baseline["expected_unique_constraints"][("users", "uq_users_email")] == {
            "key_columns": ("email",),
            "deferrable": False,
            "initially": "IMMEDIATE",
            "included_columns": (),
        }
        assert baseline["actual_checks"] == baseline["expected_checks"]
        assert baseline["expected_geometry"] == {
            ("campaign_zones", "geom"): ("MultiPolygon", 4326),
            ("location_pings", "geom"): ("Point", 4326),
        }
        assert baseline["actual_geometry"] == baseline["expected_geometry"]

        for authority, identifier, apply_statement, restore_statement in mutations:
            asyncio.run(execute_sql(migration_url, apply_statement))
            try:
                mutated = asyncio.run(fetch_catalog_authority(migration_url))
                assert mutated[f"actual_{authority}"].get(identifier) != mutated[
                    f"expected_{authority}"
                ].get(identifier)
            finally:
                asyncio.run(execute_sql(migration_url, restore_statement))
            restored = asyncio.run(fetch_catalog_authority(migration_url))
            assert restored[f"actual_{authority}"] == restored[f"expected_{authority}"]
    finally:
        asyncio.run(drop_database(migration_url))


def test_automatic_payout_bootstrap_identity_and_guards(monkeypatch):
    migration_url = asyncio.run(create_database_from_url(configured_postgres_url()))
    try:
        upgrade_to(migration_url, "head", monkeypatch)
        asyncio.run(execute(migration_url, MANUAL_BATCH))
        # Existing batches become maker-checker; nothing is automatic by default.
        assert asyncio.run(
            fetch_all(migration_url, "SELECT approval_mode, automatic_run_id FROM payout_batches")
        ) == [("maker_checker", None)]
        ((email, role, user_status, password_hash, name),) = asyncio.run(
            fetch_all(
                migration_url,
                "SELECT email, role, status, password_hash, full_name FROM users"
                f" WHERE id = '{CARDVERT_AUTOMATIC_PAYOUT_ACTOR_ID}'",
            )
        )
        assert (email, role, user_status) == (
            CARDVERT_AUTOMATIC_PAYOUT_ACTOR_EMAIL,
            "admin",
            "disabled",
        )
        assert name == "Cardvert (automatic payouts)"
        assert password_hash.startswith("$argon2") and not verify_password("", password_hash)
        assert asyncio.run(
            fetch_all(
                migration_url,
                "SELECT id, paused, reason, changed_by_user_id, actor_password_fingerprint"
                " FROM payout_automatic_controls",
            )
        ) == [(1, False, None, None, hashlib.sha256(password_hash.encode()).hexdigest())]

        invalid = (
            # A second control row, or a pause without who/why.
            "INSERT INTO payout_automatic_controls (id, paused, actor_password_fingerprint)"
            " VALUES (2, false, '" + "c" * 64 + "')",
            "UPDATE payout_automatic_controls SET paused = true",
            # A maker-checker batch may not point at a run.
            "UPDATE payout_batches SET automatic_run_id = '93000000-0000-0000-0000-000000000002'",
            # Run totals remain non-negative, without a monetary run limit.
            RUN.format(total="-0.01"),
            # An automatic batch needs its run and approval time, and no human approver.
            automatic_batch(run="NULL"),
            automatic_batch(approved_at="NULL"),
            automatic_batch(approver="'" + ADMIN + "'"),
            # Only the system actor makes automatic batches, and never manual ones.
            automatic_batch(actor=ADMIN),
            "UPDATE payout_batches SET created_by_user_id = '"
            + str(CARDVERT_AUTOMATIC_PAYOUT_ACTOR_ID)
            + "'",
            # Alert kinds are closed and a resolution needs who, when and a note.
            "INSERT INTO payout_automatic_alerts (kind, dedupe_key, detail) VALUES"
            " ('other', 'k1', '{}')",
            "INSERT INTO payout_automatic_alerts (kind, dedupe_key, detail, resolved_at) VALUES"
            " ('run_failed', 'k2', '{}', now())",
        )
        for statement in invalid:
            with pytest.raises(IntegrityError):
                asyncio.run(execute(migration_url, statement))

        asyncio.run(execute(migration_url, RUN.format(total="100")))
        asyncio.run(execute(migration_url, automatic_batch()))
    finally:
        asyncio.run(drop_database(migration_url))


ADMIN = "93000000-0000-0000-0000-00000000000a"
MANUAL_BATCH = (
    "INSERT INTO payout_batches (id, status, currency, total_amount, created_by_user_id)"
    " VALUES ('93000000-0000-0000-0000-000000000001', 'draft', 'NGN', 0, '" + ADMIN + "')"
)
RUN = (
    "INSERT INTO payout_automatic_runs (id, period_key, currency,"
    " total_amount, batch_count, line_count, exclusions, settings_fingerprint) VALUES"
    " ('93000000-0000-0000-0000-000000000002', '2026-09-28', 'NGN', {total},"
    " 1, 1, '{{}}', '" + "a" * 64 + "')"
)
AUTOMATIC_BATCH = (
    "INSERT INTO payout_batches (id, status, currency, total_amount, created_by_user_id,"
    " approval_mode, automatic_run_id, approved_at, approved_by_user_id,"
    " instruction_set_fingerprint) VALUES ('93000000-0000-0000-0000-000000000003', 'reserved',"
    " 'NGN', 100, '{actor}', 'automatic', {run}, {approved_at}, {approver}, '" + "b" * 64 + "')"
)


async def execute(url: str, statement: str, *, replica: bool = True) -> None:
    engine = create_async_engine(url, poolclass=NullPool)
    try:
        async with engine.begin() as connection:
            if replica:
                await connection.execute(text("SET LOCAL session_replication_role = replica"))
            await connection.execute(text(statement))
    finally:
        await engine.dispose()


def automatic_batch(**overrides) -> str:
    values = {
        "actor": str(CARDVERT_AUTOMATIC_PAYOUT_ACTOR_ID),
        "run": "'93000000-0000-0000-0000-000000000002'",
        "approved_at": "now()",
        "approver": "NULL",
    }
    values.update(overrides)
    return AUTOMATIC_BATCH.format(**values)
